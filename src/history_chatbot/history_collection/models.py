"""Stable records used by the 1,000-candidate collection lane."""

from __future__ import annotations

from dataclasses import asdict, dataclass, field
from enum import StrEnum
from typing import Any


class Phase(StrEnum):
    A = "A"
    B = "B"
    C = "C"
    D = "D"


PHASE_TARGETS = {Phase.A: 50, Phase.B: 200, Phase.C: 500, Phase.D: 1000}


